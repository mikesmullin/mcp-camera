#define PREVIEW_IDLE_MS (60000)  // retire 1 minute after the last grab
#define PREVIEW_CAPTURE_TIMEOUT_MS (2000)
// A UVC camera's first frames are dark and noisy while auto-exposure and
// auto-white-balance settle. They are shown in the window (so the user can see
// the feed is alive) but the daemon does not report itself ready until they are
// past, which keeps the very first camera_look from analyzing a black frame.
#define PREVIEW_WARMUP_FRAMES (15)
#define PREVIEW_IPC_ARENA (256ULL * 1024ULL)
#define PREVIEW_AUDIO_CHANNELS (1)

// ---
// State shared by the three threads

typedef struct Preview__State {
  Camera cam;
  V4l2Cap cap;

  // frame buffers, all V4l2__frameBytes() long
  Mutex frame_mtx;
  u8* live;  // newest frame from the camera   (capture writes)
  u8* frozen;  // the frame being held on screen (ipc writes, render reads)
  u8* work;  // the ipc thread's private copy to encode
  u8* render;  // the render thread's private copy of the live frame
  u8* render_frozen;  // the render thread's private copy of the frozen frame
  u8* rgba;  // live display pixels, w*h*4
  u8* rgba_frozen;  // frozen display pixels, w*h*4
  bool live_valid;
  bool frozen_valid;
  bool frozen_dirty;  // ipc set a new frozen frame the render thread has not taken
  u64 live_seq;  // bumped by capture for every new frame
  u64 render_seq;  // which live_seq the render thread last converted
  u64 grab_seq;  // bumped by ipc for every grab

  // the shutter animation: hold the captured frame, then throw it away
  bool anim_active;  // a shutter animation is in progress
  u64 freeze_until_ms;  // end of the hold, start of the toss
  u64 toss_until_ms;  // end of the toss, back to live
  bool sfx_pending;

  // lifecycle
  u64 last_grab_ms;
  u64 idle_ms;  // retire this long after the last grab
  volatile bool quitting;
  volatile bool ready;  // warmup done: frames are now worth analyzing
  u32 warmup_left;  // frames still to discard (see PREVIEW_WARMUP_FRAMES)
  volatile bool capture_failed;  // the camera went away; reported on exit

  // ipc
  int listen_fd;
  char sock_path[MAX_PATH];
  Thread ipc_thread;
  Arena* ipc_arena;

  // the jpeg encoder's output buffer, owned by the ipc thread
  u8* jpeg;
  u64 jpeg_cap;

  Mutex reg_mtx;
  Registry reg;

  Gui gui;
  Sfx sfx;
  Thread capture_thread;
  Arena* arena;
} Preview__State;

Preview__State* _G = &(Preview__State){0};

#include "app/Server.c"  // IWYU pragma: keep

// ---
// Capture thread

// publish frames into `live` until the daemon quits
static void* _Preview__captureLoop(void* userdata) {
  (void)userdata;
  u64 frame_bytes = V4l2__frameBytes(&_G->cap);
  u8* tmp = (u8*)Arena__push(_G->arena, frame_bytes);
  u32 consecutive_failures = 0;

  while (!_G->quitting) {
    if (!V4l2__read(&_G->cap, tmp, frame_bytes, PREVIEW_CAPTURE_TIMEOUT_MS)) {
      // a timeout or a short frame is normal once in a while; a long run of
      // them means the device went away and the window should not hang around
      if (++consecutive_failures >= 30) {
        LOG_ERRORF("camera stopped delivering frames; shutting down");
        _G->capture_failed = true;
        _G->quitting = true;
        break;
      }
      continue;
    }
    consecutive_failures = 0;

    Mutex__lock(&_G->frame_mtx);
    memcpy(_G->live, tmp, (size_t)frame_bytes);
    _G->live_valid = true;
    _G->live_seq++;
    if (_G->warmup_left > 0) {
      _G->warmup_left--;
      if (0 == _G->warmup_left) {
        _G->ready = true;
        LOG_INFOF("exposure settled after %d frames; ready to grab", PREVIEW_WARMUP_FRAMES);
      }
    }
    Mutex__unlock(&_G->frame_mtx);
  }

  LOG_DEBUGF("capture thread exiting");
  return NULL;
}

// ---
// Audio

// sokol_audio pulls from this on its own thread; it only ever reads the sfx
static void _Preview__audioStream(f32* samples, int frames, int channels) {
  for (int i = 0; i < frames * channels; i++) {
    samples[i] = 0.0f;
  }
  Sfx__mix(&_G->sfx, samples, (u32)frames, (u32)channels);
}

// ---
// sokol callbacks

static void _Preview__init(void) {
  sg_setup(&(sg_desc){
      .environment = sglue_environment(),
      .logger.func = slog_func,
  });
  if (!Gui__setup(&_G->gui, _G->cap.width, _G->cap.height)) {
    _G->quitting = true;
    return;
  }

  saudio_setup(&(saudio_desc){
      .sample_rate = SFX_SAMPLE_RATE,
      .num_channels = PREVIEW_AUDIO_CHANNELS,
      .stream_cb = _Preview__audioStream,
      .logger.func = slog_func,
  });
  if (!saudio_isvalid()) {
    // not fatal: the window is the important half of the feedback
    LOG_ERRORF("audio unavailable; the shutter will be silent");
  }

  char title[256];
  (void)snprintf(title, sizeof(title), "camera %s", _G->cam.name);
  Gui__place(title);
}

static void _Preview__frame(void) {
  if (_G->quitting) {
    sapp_request_quit();
    return;
  }

  u64 now = Time__now();

  // ---
  // take whatever the other threads have published, under one lock
  bool new_live = false, new_frozen = false, play_sfx = false;
  GuiScene scene = {.phase = GUI_PHASE_LIVE, .t = 0.0f};
  {
    Mutex__lock(&_G->frame_mtx);

    // the shutter timeline: hold, then throw away, then back to live
    if (_G->anim_active && _G->frozen_valid) {
      if (now < _G->freeze_until_ms) {
        scene.phase = GUI_PHASE_FROZEN;
      } else if (now < _G->toss_until_ms) {
        scene.phase = GUI_PHASE_TOSS;
        u64 span = _G->toss_until_ms - _G->freeze_until_ms;
        scene.t = span > 0 ? (f32)(now - _G->freeze_until_ms) / (f32)span : 1.0f;
      } else {
        _G->anim_active = false;
        LOG_DEBUGF("shutter animation finished; live feed only");
      }
    }

    play_sfx = _G->sfx_pending;
    _G->sfx_pending = false;

    u64 frame_bytes = V4l2__frameBytes(&_G->cap);
    // the live feed keeps updating through the whole animation, so it is
    // already current when the thrown card uncovers it
    if (_G->live_valid && _G->render_seq != _G->live_seq) {
      memcpy(_G->render, _G->live, (size_t)frame_bytes);
      _G->render_seq = _G->live_seq;
      new_live = true;
    }
    // the frozen image is copied exactly once per grab
    if (_G->frozen_dirty) {
      memcpy(_G->render_frozen, _G->frozen, (size_t)frame_bytes);
      _G->frozen_dirty = false;
      new_frozen = true;
    }
    Mutex__unlock(&_G->frame_mtx);
  }

  if (play_sfx) {
    Sfx__trigger(&_G->sfx);
  }

  // convert and upload outside the lock
  if (new_live) {
    Gui__yuyvToRgba(_G->render, _G->rgba, _G->cap.width, _G->cap.height);
    Gui__uploadLive(&_G->gui, _G->rgba);
  }
  if (new_frozen) {
    Gui__yuyvToRgba(_G->render_frozen, _G->rgba_frozen, _G->cap.width, _G->cap.height);
    Gui__uploadFrozen(&_G->gui, _G->rgba_frozen);
  }

  Gui__draw(&_G->gui, &scene);

  // ---
  // retire after the idle window
  if (now - _G->last_grab_ms > _G->idle_ms) {
    LOG_INFOF("idle for %lu ms; retiring", (unsigned long)(now - _G->last_grab_ms));
    _G->quitting = true;
    sapp_request_quit();
  }
}

static void _Preview__cleanup(void) {
  // the sweep is the promise camera_look makes about transient frames, so it
  // runs on every exit path that reaches cleanup
  Mutex__lock(&_G->reg_mtx);
  (void)Registry__sweep(&_G->reg);
  Mutex__unlock(&_G->reg_mtx);

  Server__stop();
  Thread__join(&_G->capture_thread);
  V4l2__close(&_G->cap);

  saudio_shutdown();
  Gui__shutdown(&_G->gui);
  sg_shutdown();
  // the exit code stays 0 either way (the window closing is not an error the
  // MCP client can act on), but the reason belongs in the log
  if (_G->capture_failed) {
    LOG_ERRORF("preview for %s exited after the camera stopped responding", _G->cam.name);
  } else {
    LOG_INFOF("preview for %s exited cleanly", _G->cam.name);
  }
}

static void _Preview__event(const sapp_event* ev) {
  // closing the window by hand is a legitimate way to dismiss the preview
  if (SAPP_EVENTTYPE_QUIT_REQUESTED == ev->type) {
    _G->quitting = true;
    return;
  }
  if (SAPP_EVENTTYPE_KEY_DOWN == ev->type && SAPP_KEYCODE_ESCAPE == ev->key_code) {
    _G->quitting = true;
    sapp_request_quit();
  }
}

// ---
// Startup

static void _Preview__onSignal(int sig) {
  // let the event loop unwind so cleanup (and the sweep) still runs
  Console__error("[camera] caught signal %d, closing the preview\n", sig);
  _G->quitting = true;
}

// allocate every shared buffer up front, from one arena
static bool _Preview__allocBuffers(void) {
  u64 frame_bytes = V4l2__frameBytes(&_G->cap);
  u64 rgba_bytes = (u64)_G->cap.width * (u64)_G->cap.height * 4ULL;
  _G->jpeg_cap = Jpeg__boundLen(_G->cap.width, _G->cap.height);

  // 5 YUYV buffers + the capture thread's own + 2 RGBA + the jpeg output
  u64 need = frame_bytes * 7ULL + rgba_bytes * 2ULL + _G->jpeg_cap + (1ULL << 20);
  _G->arena = Arena__allocZ(need);
  if (NULL == _G->arena) {
    LOG_ERRORF("cannot allocate %llu bytes of frame buffers", (unsigned long long)need);
    return false;
  }

  _G->live = (u8*)Arena__push(_G->arena, frame_bytes);
  _G->frozen = (u8*)Arena__push(_G->arena, frame_bytes);
  _G->work = (u8*)Arena__push(_G->arena, frame_bytes);
  _G->render = (u8*)Arena__push(_G->arena, frame_bytes);
  _G->render_frozen = (u8*)Arena__push(_G->arena, frame_bytes);
  _G->rgba = (u8*)Arena__push(_G->arena, rgba_bytes);
  _G->rgba_frozen = (u8*)Arena__push(_G->arena, rgba_bytes);
  _G->jpeg = (u8*)Arena__push(_G->arena, _G->jpeg_cap);

  _G->ipc_arena = Arena__allocZ(PREVIEW_IPC_ARENA);
  return NULL != _G->ipc_arena;
}

// parsed command line
typedef struct {
  char camera_id[MAX_CAM_NAME];
  u32 width, height;
  u32 win_w, win_h;
  char write_sfx[MAX_PATH];
} PreviewArgs;

static void _Preview__usage(void) {
  Console__out(
      "usage: camera_preview [--camera ID] [--size WxH] [--window WxH] [--write-sfx PATH]\n"
      "\n"
      "Owns one camera, shows its feed, and serves frames to camera_mcp over a\n"
      "Unix socket. Normally started automatically by camera_mcp.\n"
      "\n"
      "environment:\n"
      "  CAMERA_DIR             transient frame directory (default /tmp/camera)\n"
      "  CAMERA_SFX             16-bit PCM WAV to use for the shutter\n"
      "  CAMERA_PREVIEW_X/_Y    override the window position\n"
      "  CAMERA_PREVIEW_ONTOP   set to 0 to not keep the window on top\n");
}

// parse "WxH" into two dimensions
static bool _Preview__parseSize(const char* s, u32* w, u32* h) {
  char tmp[32];
  if (!cstr__copy(tmp, (u32)sizeof(tmp), s)) {
    return false;
  }
  u32 n = cstr__len(tmp);
  for (u32 i = 0; i < n; i++) {
    if ('x' == tmp[i] || 'X' == tmp[i]) {
      tmp[i] = 0;
      return cstr__toU32(tmp, w) && cstr__toU32(tmp + i + 1, h) && *w > 0 && *h > 0;
    }
  }
  return false;
}

static bool _Preview__parseArgs(int argc, char* argv[], PreviewArgs* out) {
  memset(out, 0, sizeof(*out));
  out->width = 640;
  out->height = 480;
  out->win_w = GUI_DEFAULT_W;
  out->win_h = GUI_DEFAULT_H;

  for (int i = 1; i < argc; i++) {
    if (cstr__eq(argv[i], "--camera") && i + 1 < argc) {
      (void)cstr__copy(out->camera_id, (u32)sizeof(out->camera_id), argv[++i]);
    } else if (cstr__eq(argv[i], "--size") && i + 1 < argc) {
      if (!_Preview__parseSize(argv[++i], &out->width, &out->height)) {
        Console__error("bad --size (expected WxH)\n");
        return false;
      }
    } else if (cstr__eq(argv[i], "--window") && i + 1 < argc) {
      if (!_Preview__parseSize(argv[++i], &out->win_w, &out->win_h)) {
        Console__error("bad --window (expected WxH)\n");
        return false;
      }
    } else if (cstr__eq(argv[i], "--write-sfx") && i + 1 < argc) {
      (void)cstr__copy(out->write_sfx, (u32)sizeof(out->write_sfx), argv[++i]);
    } else if (cstr__eq(argv[i], "--help")) {
      _Preview__usage();
      return false;
    } else {
      Console__error("unknown argument: %s (try --help)\n", argv[i]);
      return false;
    }
  }
  return true;
}

// sokol owns main(), so startup happens here and the window is described back
sapp_desc sokol_main(int argc, char* argv[]) {
  Console__init();
  Jpeg__init();
  (void)signal(SIGINT, _Preview__onSignal);
  (void)signal(SIGTERM, _Preview__onSignal);
  (void)signal(SIGPIPE, SIG_IGN);

  PreviewArgs args;
  if (!_Preview__parseArgs(argc, argv, &args)) {
    exit(2);
  }

  Sfx__init(&_G->sfx);
  if (0 != args.write_sfx[0]) {
    // a maintenance path: dump the built-in click so it can be edited
    exit(Sfx__writeWav(&_G->sfx, args.write_sfx) ? 0 : 1);
  }

  // which camera?
  CameraList cams;
  if (!CamId__list(&cams) || 0 == cams.ct) {
    Console__error("[camera] ERROR no capture-capable camera found\n");
    exit(1);
  }
  if (!CamId__resolve(&cams, args.camera_id, &_G->cam)) {
    Console__error("[camera] ERROR no camera matches '%s'\n", args.camera_id);
    exit(1);
  }

  if (!Mutex__create(&_G->frame_mtx) || !Mutex__create(&_G->reg_mtx)) {
    Console__error("[camera] ERROR cannot create mutexes\n");
    exit(1);
  }
  Registry__init(&_G->reg);
  _G->listen_fd = -1;
  _G->warmup_left = PREVIEW_WARMUP_FRAMES;

  // the idle timeout is the contract behind "transient" frames; it is
  // overridable mainly so the sweep can be exercised in tests
  _G->idle_ms = PREVIEW_IDLE_MS;
  {
    const char* v = getenv("CAMERA_IDLE_MS");
    u32 ms = 0;
    if (NULL != v && 0 != v[0] && cstr__toU32(v, &ms) && ms >= 1000) {
      _G->idle_ms = ms;
      LOG_INFOF("idle timeout overridden to %lu ms", (unsigned long)ms);
    }
  }

  // claim the camera BEFORE opening a window, so a busy device fails fast and
  // the user never sees an empty frame
  if (!V4l2__open(&_G->cap, _G->cam.path, args.width, args.height)) {
    exit(1);
  }
  if (!V4l2__start(&_G->cap)) {
    V4l2__close(&_G->cap);
    exit(1);
  }
  if (!_Preview__allocBuffers()) {
    V4l2__close(&_G->cap);
    exit(1);
  }

  // the idle clock starts now; camera_mcp grabs a frame immediately after
  // spawning us, which re-arms it
  _G->last_grab_ms = Time__now();

  if (!Thread__create(&_G->capture_thread, _Preview__captureLoop, NULL)) {
    Console__error("[camera] ERROR cannot start the capture thread\n");
    V4l2__close(&_G->cap);
    exit(1);
  }
  if (!Server__start()) {
    _G->quitting = true;
    Thread__join(&_G->capture_thread);
    V4l2__close(&_G->cap);
    exit(1);
  }

  char* title = (char*)Arena__push(_G->arena, 256);
  (void)snprintf(title, 256, "camera %s", _G->cam.name);

  return (sapp_desc){
      .init_cb = _Preview__init,
      .frame_cb = _Preview__frame,
      .cleanup_cb = _Preview__cleanup,
      .event_cb = _Preview__event,
      .width = (int)args.win_w,
      .height = (int)args.win_h,
      .window_title = title,
      // our own camera glyph rather than sokol's default; this becomes the
      // window's _NET_WM_ICON, which is what the taskbar shows
      .icon.sokol_default = false,
      .icon.images =
          {
              {.width = 16, .height = 16, .pixels = SAPP_RANGE(ICON_16)},
              {.width = 32, .height = 32, .pixels = SAPP_RANGE(ICON_32)},
              {.width = 64, .height = 64, .pixels = SAPP_RANGE(ICON_64)},
          },
      .logger.func = slog_func,
  };
}
