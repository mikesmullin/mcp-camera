// Single Compilation Unit 2 (Unity Build: camera_preview) -----
//
// The preview daemon. It owns the camera exclusively (V4L2 permits only one
// streaming opener), shows the live feed on the user's desktop, and serves
// frames to camera_mcp over a Unix socket.
//
// Three threads:
//   main     sokol event loop -- converts and draws the current frame
//   capture  blocks in V4L2 and publishes the newest frame
//   ipc      accepts grab requests, freezes a frame, encodes and writes it
//
// It retires itself: PREVIEW_IDLE_MS after the last grab it deletes every
// non-persisted frame it wrote and exits 0.

